'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const skill=read('.agents/skills/gpt-chat-maximize/SKILL.md');
const work=read('.agents/skills/gpt-chat-maximize/references/SELF_WORKSTREAMS.md');
const agents=read('AGENTS.md');
const blueprint=JSON.parse(read('content/career-prep-quality-blueprint.json'));
assert(skill.startsWith('---\nname: gpt-chat-maximize\n'), 'skill frontmatter and slug');
assert(skill.includes('description:'), 'skill summary available for agents');
assert(agents.includes('.agents/skills/gpt-chat-maximize/SKILL.md'), 'root AGENTS.md points to actual Skill');
assert(agents.includes('SELF'), 'correct project');
for(const role of ['Worker A / PE','Worker B / VC','Worker C / Consulting','Integrator / QA'])assert(skill.includes(role),'missing operational role '+role);
const branches=['feat/self-career-case-pe-20261022','feat/self-career-case-vc-20261022','feat/self-career-case-consulting-20261022'];
for(const branch of branches)assert(work.includes(branch),'missing worker branch '+branch);
for(const dir of ['content/career-cases/pe/**','content/career-cases/vc/**','content/career-cases/consulting/**'])assert(work.includes(dir),'missing owned path '+dir);
for(const p of ['app.js','career-learning.js','content/career-learning.json','supabase/**','index.html','.github/workflows/**'])assert(work.includes(p),'missing shared path protection '+p);
for(const p of ['Supabase','main','PR','RLS'])assert(skill.includes(p),'missing integration constraint '+p);
assert(work.includes('GptChatMaximize')&&work.includes('Phase 2'),'matches latest workstream');
assert(work.includes('do not store sealed blind-assessment answers') || work.includes('do not store sealed blind-assessment answers'.replace('d','D')),'no client-side answer-key leaks');
assert(blueprint.tracks.length===3 && blueprint.tracks.every(t=>t.skills.length>=12),'Skill anchored to current Phase 1 blueprint');
assert(!skill.includes('AUTO-MERGE ALL'), 'no unguarded auto merges');
console.log('PASS GptChatMaximize: skill routing, branch isolation, 3 ownership scopes, protected shared files, Supabase gate and phase contract');
